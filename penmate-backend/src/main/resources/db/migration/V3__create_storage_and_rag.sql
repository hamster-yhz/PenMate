-- Child partitions and metric-specific HNSW indexes are provisioned only by the
-- trusted pgvector infrastructure adapter after dimension detection.
CREATE TABLE rag_vectors_f32 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    embedding_space_id BIGINT NOT NULL,
    vector_id BIGINT NOT NULL,
    chunk_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    index_build_id BIGINT NOT NULL,
    embedding vector NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (embedding_space_id, id),
    CONSTRAINT uk_rag_vectors_f32_id UNIQUE (embedding_space_id, vector_id),
    CONSTRAINT uk_rag_vectors_f32_chunk UNIQUE (embedding_space_id, chunk_id)
) PARTITION BY LIST (embedding_space_id);

CREATE TABLE rag_vectors_f16 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    embedding_space_id BIGINT NOT NULL,
    vector_id BIGINT NOT NULL,
    chunk_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    index_build_id BIGINT NOT NULL,
    embedding halfvec NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (embedding_space_id, id),
    CONSTRAINT uk_rag_vectors_f16_id UNIQUE (embedding_space_id, vector_id),
    CONSTRAINT uk_rag_vectors_f16_chunk UNIQUE (embedding_space_id, chunk_id)
) PARTITION BY LIST (embedding_space_id);

