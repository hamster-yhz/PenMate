CREATE TABLE rag_index_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_index_id BIGINT NOT NULL,
    index_build_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    source_id BIGINT NOT NULL,
    source_revision VARCHAR(128) NOT NULL,
    source_title VARCHAR(255) NOT NULL,
    source_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    content_checksum CHAR(64) NULL,
    character_count BIGINT NOT NULL DEFAULT 0,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    activated_at TIMESTAMPTZ(3) NULL,
    superseded_at TIMESTAMPTZ(3) NULL,
    last_error_code VARCHAR(96) NULL,
    last_error_message VARCHAR(500) NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_rag_index_sources_id UNIQUE (source_index_id),
    CONSTRAINT uk_rag_index_sources_revision UNIQUE (index_build_id, source_type, source_id, source_revision),
    CONSTRAINT ck_rag_index_source_type CHECK (source_type IN ('STORY_BIBLE_NODE', 'MANUSCRIPT_CHUNK', 'KNOWLEDGE_DOCUMENT'))
);

CREATE UNIQUE INDEX uk_rag_index_sources_active
    ON rag_index_sources (index_build_id, source_type, source_id)
    WHERE active = TRUE AND superseded_at IS NULL;
CREATE INDEX idx_rag_source_project_status ON rag_index_sources (project_id, source_status, updated_at);

