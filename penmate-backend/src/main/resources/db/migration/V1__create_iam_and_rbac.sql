CREATE TABLE IF NOT EXISTS iam_menus (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id BIGINT NOT NULL,
    parent_id BIGINT NULL,
    title VARCHAR(100) NOT NULL,
    path VARCHAR(255) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    permission_code VARCHAR(120) NULL,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    deleted_at TIMESTAMPTZ(3) NULL,
    CONSTRAINT uk_iam_menus_menu_id UNIQUE (menu_id)
);

CREATE INDEX idx_menu_parent_sort ON iam_menus (parent_id, sort_order);
CREATE INDEX idx_menu_visible ON iam_menus (visible, deleted_at);
