-- Chapter versions are immutable OSS snapshots. Project ownership is defined only
-- by novel_projects.owner_user_id; there is no collaboration membership table.
CREATE TABLE IF NOT EXISTS novel_chapter_versions (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapter_version_id BIGINT NOT NULL,
    chapter_id BIGINT NOT NULL,
    version_no INTEGER NOT NULL,
    change_type VARCHAR(32) NOT NULL,
    change_reason VARCHAR(255) NULL,
    snapshot_object_key VARCHAR(500) NOT NULL,
    snapshot_etag VARCHAR(128) NULL,
    snapshot_size BIGINT NULL,
    snapshot_checksum VARCHAR(128) NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_novel_chapter_versions_version_id UNIQUE (chapter_version_id),
    CONSTRAINT uk_chapter_version_no UNIQUE (chapter_id, version_no)
);

CREATE INDEX idx_chapter_versions_chapter_created ON novel_chapter_versions (chapter_id, created_at);



