CREATE TABLE IF NOT EXISTS novel_projects (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    summary TEXT NULL,
    status SMALLINT NOT NULL DEFAULT 1,
    structure_revision BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    deleted_at TIMESTAMPTZ(3) NULL,
    CONSTRAINT uk_novel_projects_project_id UNIQUE (project_id)
);

CREATE INDEX idx_novel_owner_status ON novel_projects (owner_user_id, status, deleted_at);

CREATE TABLE IF NOT EXISTS agent_approval_requests (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_request_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    run_id BIGINT NULL,
    approval_type VARCHAR(40) NOT NULL,
    payload_json JSONB NOT NULL,
    risk_level SMALLINT NOT NULL DEFAULT 2,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    requested_by BIGINT NOT NULL,
    reviewed_by BIGINT NULL,
    reviewed_at TIMESTAMPTZ(3) NULL,
    review_comment VARCHAR(500) NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_agent_approval_requests_request_id UNIQUE (approval_request_id)
);

CREATE INDEX idx_approval_project_status ON agent_approval_requests (project_id, status, created_at);
CREATE INDEX idx_approval_run ON agent_approval_requests (run_id);

CREATE TABLE IF NOT EXISTS agent_approval_actions (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_action_id BIGINT NOT NULL,
    request_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL,
    operator_id BIGINT NOT NULL,
    comment VARCHAR(500) NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT uk_agent_approval_actions_action_id UNIQUE (approval_action_id)
);

CREATE INDEX idx_approval_actions_request ON agent_approval_actions (request_id, created_at);



